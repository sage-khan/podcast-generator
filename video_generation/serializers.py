class KlingLipsyncGenerateSerializer(serializers.Serializer):
    """
    Serializer for generating lip-sync videos with Kling
    """
    # Text-based input fields
    text = serializers.CharField(required=False, allow_blank=True, 
                                help_text="Text content for lip sync (if not using audio)")
    voice_id = serializers.CharField(required=False, default="en_AOT", 
                                   help_text="Voice ID for speech synthesis (if using text and not audio)")
    voice_speed = serializers.FloatField(required=False, default=1.0, 
                                       help_text="Speech rate (only used if using text and not audio)")
    
    # Audio-based input fields
    audio_file = serializers.URLField(required=False, allow_null=True, 
                                    help_text="Audio file for lip sync. Must be .mp3, .wav, .m4a, or .aac and less than 5MB")
    
    # Video source fields
    video_id = serializers.CharField(required=False, allow_null=True, 
                                   help_text="ID of a video generated by Kling. Cannot be used with video_url")
    video_url = serializers.URLField(required=False, allow_null=True, 
                                   help_text="URL of a video for lip syncing. Cannot be used with video_id")
    
    # Legacy fields - kept for backward compatibility 
    audio_url = serializers.URLField(required=False, allow_null=True, 
                                   help_text="Legacy: URL to the audio file for lip-sync")
    image_url = serializers.URLField(required=False, allow_null=True, 
                                   help_text="Legacy: URL to the image to animate with lip-sync")
    
    # Additional fields
    prompt = serializers.CharField(required=False, allow_blank=True, 
                                 help_text="Optional additional prompt for generation")
    negative_prompt = serializers.CharField(required=False, allow_blank=True, 
                                          help_text="Things you do not want to see in the video")
    client_webhook_url = serializers.URLField(required=False, allow_null=True, 
                                            help_text="URL to send webhook updates to")
    
    def validate_voice_speed(self, value):
        """Validate that voice_speed is between 0.8 and 2"""
        if value < 0.8 or value > 2:
            raise serializers.ValidationError("voice_speed must be between 0.8 and 2")
        return value
        
    def validate(self, data):
        """Validate input combinations"""
        # Legacy mode validation
        audio_url = data.get('audio_url')
        image_url = data.get('image_url')
        
        # New schema mode validation
        text = data.get('text')
        audio_file = data.get('audio_file')
        video_id = data.get('video_id')
        video_url = data.get('video_url')
        
        # Check if we're using legacy mode
        if audio_url and image_url:
            # Legacy mode, no additional validation needed
            return data
            
        # Check that we have either text or audio_file
        if not text and not audio_file and not audio_url:
            raise serializers.ValidationError(
                "Either 'text' or 'audio_file' must be provided for lip syncing")
        
        # Check that we have either video_id or video_url
        if not video_id and not video_url and not image_url:
            raise serializers.ValidationError(
                "Either 'video_id' or 'video_url' must be provided for lip syncing")
                
        # Check that video_id and video_url are not both provided
        if video_id and video_url:
            raise serializers.ValidationError(
                "Cannot use both 'video_id' and 'video_url' together")
                
        return data


