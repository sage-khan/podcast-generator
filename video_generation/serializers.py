from rest_framework import serializers
from video_generation.models import KlingVideoJob, KlingLipsyncJob, GoogleVeo3VideoJob


class KlingVideoGenerateSerializer(serializers.Serializer):
    """
    Serializer for generating videos with Kling
    """
    prompt = serializers.CharField(required=True, help_text="Text prompt for video generation")
    negative_prompt = serializers.CharField(required=False, allow_blank=True, help_text="Things you do not want to see in the video")
    aspect_ratio = serializers.CharField(required=False, default="16:9", help_text="Aspect ratio of the video")
    start_image = serializers.URLField(required=False, allow_null=True, help_text="First frame of the video")
    end_image = serializers.URLField(required=False, allow_null=True, help_text="Last frame of the video")
    reference_images = serializers.ListField(
        child=serializers.URLField(),
        required=False,
        default=list,
        help_text="Reference images to use in video generation (up to 4 images)"
    )
    cfg_scale = serializers.FloatField(required=False, default=0.5, help_text="Flexibility in video generation")
    duration = serializers.IntegerField(required=False, default=5, help_text="Duration of the video in seconds (5 or 10)")
    client_webhook_url = serializers.URLField(required=False, allow_null=True, help_text="URL to send webhook updates to")
    
    def validate_duration(self, value):
        """Validate that duration is either 5 or 10 seconds"""
        if value not in [5, 10]:
            raise serializers.ValidationError("Duration must be either 5 or 10 seconds")
        return value
        
    def validate(self, data):
        """Validate that either start_image or end_image is provided"""
        start_image = data.get('start_image')
        end_image = data.get('end_image')
        
        if not start_image and not end_image:
            raise serializers.ValidationError("Either start_image or end_image is required")
            
        return data


